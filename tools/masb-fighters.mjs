export function lineFighter(drawing, name) {
  const figure=drawings[drawing];
  if(!figure)throw new Error(`Unknown illustrative fighter: ${drawing}`);
  const label=String(name).replaceAll('&','&amp;').replaceAll('"','&quot;').replaceAll('<','&lt;');
  const paths=(items,cls)=>`<g class="${cls}">${items.map(d=>`<path class="fighter-line" pathLength="1" d="${d}"/>`).join('')}</g>`;
  return `<svg class="process-fighter line-fighter" data-line-fighter="${drawing}" viewBox="0 0 360 440" width="360" height="440" role="img" aria-label="${label} — illustrative line drawing" xmlns="http://www.w3.org/2000/svg">${paths(figure.outline,'fighter-outline')}${paths(figure.accents,'fighter-accent')}</svg>`;
}

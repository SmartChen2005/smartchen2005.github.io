const drawings = { guardian, duelist };
export function lineFighter(drawing, name) {
  const figure = drawings[drawing];
  if (!figure) throw new Error(`Unknown illustrative fighter: ${drawing}`);
  const label = String(name).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
  return `<svg class="process-fighter line-fighter" data-line-fighter="${drawing}" viewBox="0 0 360 480" width="360" height="480" role="img" aria-label="${label} — illustrative ink drawing" xmlns="http://www.w3.org/2000/svg">${figure()}</svg>`;
}
